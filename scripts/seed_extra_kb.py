def main() -> None:
    kb = json.loads((ROOT / "core" / "data" / "kb.json").read_text(encoding="utf-8"))
    existing = {e.get("id") for e in kb.get("kb") or []}
    added = 0
    for e in ENTRIES:
        if e["id"] in existing:
            for i, cur in enumerate(kb["kb"]):
                if cur.get("id") == e["id"]:
                    kb["kb"][i] = e
                    break
        else:
            kb["kb"].append(e)
            added += 1
    (ROOT / "core" / "data" / "kb.json").write_text(
        json.dumps(kb, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"kb entries: {len(kb['kb'])} (added {added})")


if __name__ == "__main__":
    main()
